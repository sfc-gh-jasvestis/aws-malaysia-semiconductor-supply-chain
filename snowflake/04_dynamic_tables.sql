  TARGET_LAG = '30 days' WAREHOUSE = TOURISM_WH
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH thresh AS (
  SELECT PERCENTILE_CONT(0.09) WITHIN GROUP (ORDER BY KPI_ON_TIME_DELIVERY) AS T
  FROM RAW.PURCHASE_ORDERS
)
SELECT
  e.ID AS ENTITY_ID,
  e.NAME AS ENTITY_NAME,
  e.REGION,
  e.CATEGORY,
  e.STATUS,
  COUNT(*) AS EVENT_COUNT,
  SUM(CASE WHEN f.KPI_ON_TIME_DELIVERY <= (SELECT T FROM thresh) THEN 1 ELSE 0 END) AS ALERT_COUNT,
  ROUND(AVG(f.KPI_ON_TIME_DELIVERY), 2) AS AVG_ON_TIME_DELIVERY,
  ROUND(AVG(f.KPI_COMPONENT_SHORTAGE), 2) AS AVG_COMPONENT_SHORTAGE,
  ROUND(AVG(f.KPI_LEAD_TIME_AVG), 2) AS AVG_LEAD_TIME,
  ROUND(AVG(f.KPI_BUFFER_STOCK), 2) AS AVG_BUFFER_STOCK,
  ROUND(AVG(f.KPI_ALTERNATIVES), 2) AS AVG_ALTERNATIVES
FROM RAW.PURCHASE_ORDERS f
JOIN RAW.ASEAN_TRADE e ON e.ID = f.ENTITY_ID
CROSS JOIN thresh
GROUP BY e.ID, e.NAME, e.REGION, e.CATEGORY, e.STATUS;

